// Writes the license texts of every crate locked in packages/local-intelligence/helper/Cargo.lock,
// which the desktop runtime ships compiled into the local AI helper. Run after changing the lock:
//   node tools/local-intelligence/helper-notices.ts
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

interface Crate {
  name: string;
  version: string;
  license: string | null;
  manifest_path: string;
  source: string | null;
}

const root = resolve(import.meta.dirname, '../..');
const output = join(root, 'THIRD-PARTY-NOTICES/local-ai-helper-crates.txt');
const metadata = execFileSync(
  'cargo',
  [
    'metadata',
    '--format-version',
    '1',
    '--locked',
    '--manifest-path',
    join(root, 'packages/local-intelligence/helper/Cargo.toml'),
  ],
  { encoding: 'utf8', maxBuffer: 64 << 20 },
);
const crates = (JSON.parse(metadata) as { packages: Crate[] }).packages
  .filter((crate) => crate.source)
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  'Rust crates in the Corral local AI helper',
  '',
  'Generated by tools/local-intelligence/helper-notices.ts from packages/local-intelligence/helper/Cargo.lock.',
  'It lists every locked crate, including those used only to build the helper or only on Windows.',
  '',
  ...crates.map((crate) => `${crate.name} ${crate.version}: ${crate.license}`),
];
const seen = new Map<string, string>();
for (const crate of crates) {
  assert(crate.license, `${crate.name} ${crate.version} declares no license`);
  const dir = dirname(crate.manifest_path);
  const files = readdirSync(dir)
    .filter((name) => /^(licen[cs]e|copying|unlicense|notice)/i.test(name))
    .sort();
  assert(files.length > 0, `${crate.name} ${crate.version} ships no license file`);
  for (const file of files) {
    const text = readFileSync(join(dir, file), 'utf8').replaceAll('\r\n', '\n').trimEnd();
    const hash = createHash('sha256').update(text).digest('hex');
    const label = `${crate.name} ${crate.version}, ${file}`;
    lines.push('', `----- ${label} -----`, '');
    const same = seen.get(hash);
    if (same) lines.push(`Same text as ${same}.`);
    else {
      seen.set(hash, label);
      lines.push(text);
    }
  }
}
writeFileSync(output, `${lines.join('\n')}\n`);
console.log(`Wrote the notices of ${crates.length} crates to ${output}`);
